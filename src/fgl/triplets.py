def unique_triplets(triplets=LEGACY_TRIPLETS) -> np.ndarray:
    """Drop exact duplicates while keeping first-seen order."""
    seen, out = set(), []
    for t in triplets:
        if t not in seen:
            seen.add(t)
            out.append(t)
    return np.asarray(out, dtype=np.int64)


def triplet_landmarks(triplets=LEGACY_TRIPLETS) -> np.ndarray:
    """Sorted unique landmark indices referenced by a triplet list."""
    return np.unique(np.asarray(triplets, dtype=np.int64).ravel())
